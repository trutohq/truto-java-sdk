#!/usr/bin/env python3
"""Emit the Java model classes for the Truto SDK from codegen/models.json.

Usage (from the repo root):

    python3 codegen/normalize_spec.py spec/openapi.json > codegen/models.json
    python3 codegen/generate_java.py codegen/models.json src/main/java/one/truto/sdk/models

Every file this script writes starts with a "DO NOT EDIT" header. Files in the
output directory that carry that header but no longer correspond to a model are
deleted, so a model removed from the spec disappears from the SDK. Hand-written
files (no header) are never touched.

Mapping rules (see SDK_CONTRACT.md section 2):
  object -> final class with Jackson field annotations, getters, setters and
            fluent setters; lenient decoding via @JsonIgnoreProperties.
            An object with no fields but `additional` set becomes a class that
            extends LinkedHashMap<String, V>.
  enum   -> open enum: final class wrapping a String with known constants.
  union  -> wrapper over the raw JsonNode with an asX() accessor per variant.
"""
import json
import os
import re
import sys

PACKAGE = "one.truto.sdk.models"
HEADER = "// DO NOT EDIT - generated by codegen/generate_java.py from codegen/models.json.\n"

JAVA_KEYWORDS = {
    "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char",
    "class", "const", "continue", "default", "do", "double", "else", "enum",
    "extends", "final", "finally", "float", "for", "goto", "if", "implements",
    "import", "instanceof", "int", "interface", "long", "native", "new",
    "package", "private", "protected", "public", "return", "short", "static",
    "strictfp", "super", "switch", "synchronized", "this", "throw", "throws",
    "transient", "try", "void", "volatile", "while", "true", "false", "null",
    "var", "record", "yield", "sealed", "permits",
}

# Names generated classes use from other packages / java.lang; a field type
# never collides with these because model names are checked below.
RESERVED_CLASS_NAMES = {
    "Object", "String", "Class", "System", "Long", "Double", "Boolean", "List",
    "Map", "LinkedHashMap", "JsonNode", "Objects", "Json", "Override",
    "TrutoRecord",
}


def camel(name):
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", name) if p]
    if not parts:
        return "value"
    out = parts[0][0].lower() + parts[0][1:]
    for p in parts[1:]:
        out += p[0].upper() + p[1:]
    if out[0].isdigit():
        out = "n" + out
    if out in JAVA_KEYWORDS:
        out += "_"
    return out


def upper_first(s):
    return s[0].upper() + s[1:]


def constant_name(value):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()
    if not s:
        s = "EMPTY"
    if s[0].isdigit():
        s = "N" + s
    if s.lower() in JAVA_KEYWORDS:
        s += "_"
    return s


def javadoc(text, indent=""):
    text = (text or "").strip()
    if not text:
        return ""
    para = re.split(r"\n\s*\n", text)[0].strip()
    para = (para.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace("*/", "*&#47;").replace("@", "&#64;").replace("\\u", "\\\\u"))
    lines = [ln.rstrip() for ln in para.splitlines()]
    out = indent + "/**\n"
    for ln in lines:
        out += indent + " * " + ln.strip() + "\n" if ln.strip() else indent + " *\n"
    out += indent + " */\n"
    return out


def java_type(t, boxed=True):
    k = t["kind"]
    if k == "string":
        return "String"
    if k == "integer":
        return "Long" if boxed else "long"
    if k == "number":
        return "Double" if boxed else "double"
    if k == "boolean":
        return "Boolean" if boxed else "boolean"
    if k == "any":
        return "JsonNode"
    if k == "array":
        return "List<%s>" % java_type(t["items"])
    if k == "map":
        return "Map<String, %s>" % java_type(t["values"])
    if k == "ref":
        return t["name"]
    raise ValueError("unknown TypeRef kind %r" % k)


def uses(t, acc):
    k = t["kind"]
    if k == "any":
        acc.add("JsonNode")
    elif k == "array":
        acc.add("List")
        uses(t["items"], acc)
    elif k == "map":
        acc.add("Map")
        uses(t["values"], acc)


def imports_block(names):
    table = {
        "JsonNode": "com.fasterxml.jackson.databind.JsonNode",
        "List": "java.util.List",
        "Map": "java.util.Map",
        "LinkedHashMap": "java.util.LinkedHashMap",
        "Objects": "java.util.Objects",
        "JsonProperty": "com.fasterxml.jackson.annotation.JsonProperty",
        "JsonInclude": "com.fasterxml.jackson.annotation.JsonInclude",
        "JsonIgnoreProperties": "com.fasterxml.jackson.annotation.JsonIgnoreProperties",
        "JsonAutoDetect": "com.fasterxml.jackson.annotation.JsonAutoDetect",
        "JsonCreator": "com.fasterxml.jackson.annotation.JsonCreator",
        "JsonValue": "com.fasterxml.jackson.annotation.JsonValue",
        "Json": "one.truto.sdk.Json",
    }
    lines = sorted("import %s;" % table[n] for n in names)
    return "\n".join(lines) + "\n\n" if lines else ""


def emit_object(m):
    name = m["name"]
    fields = m["fields"]
    if not fields:
        value = java_type(m["additional"]) if m.get("additional") else "JsonNode"
        imp = {"LinkedHashMap", "JsonIgnoreProperties"}
        uses(m["additional"] or {"kind": "any"}, imp)
        body = javadoc(m.get("description"))
        body += "@JsonIgnoreProperties(ignoreUnknown = true)\n"
        body += "public final class %s extends LinkedHashMap<String, %s> {\n" % (name, value)
        body += "    private static final long serialVersionUID = 1L;\n\n"
        body += "    /** Creates an empty instance. */\n"
        body += "    public %s() {\n        super();\n    }\n}\n" % name
        return imports_block(imp) + body

    imp = {"JsonProperty", "JsonInclude", "JsonIgnoreProperties", "JsonAutoDetect", "Objects", "Json"}
    props = []
    seen = set()
    for f in fields:
        prop = camel(f["name"])
        base, i = prop, 2
        while prop in seen:
            prop = "%s%d" % (base, i)
            i += 1
        seen.add(prop)
        optional = (not f["required"]) or f["nullable"]
        jt = java_type(f["type"], boxed=optional)
        uses(f["type"], imp)
        props.append((f, prop, jt))

    out = javadoc(m.get("description"))
    out += "@JsonInclude(JsonInclude.Include.NON_NULL)\n"
    out += "@JsonIgnoreProperties(ignoreUnknown = true)\n"
    out += ("@JsonAutoDetect(fieldVisibility = JsonAutoDetect.Visibility.ANY, "
            "getterVisibility = JsonAutoDetect.Visibility.NONE, "
            "isGetterVisibility = JsonAutoDetect.Visibility.NONE, "
            "setterVisibility = JsonAutoDetect.Visibility.NONE)\n")
    out += "public final class %s {\n" % name
    for f, prop, jt in props:
        out += javadoc(f.get("description"), "    ")
        out += '    @JsonProperty("%s")\n' % f["name"].replace("\\", "\\\\").replace('"', '\\"')
        out += "    private %s %s;\n\n" % (jt, prop)
    out += "    /** Creates an empty instance. */\n"
    out += "    public %s() {\n        // all fields start unset\n    }\n\n" % name
    for f, prop, jt in props:
        up = upper_first(prop.rstrip("_")) if prop.endswith("_") else upper_first(prop)
        wire = f["name"]
        out += "    /**\n     * Returns {@code %s}.\n     *\n     * @return the value\n     */\n" % wire.replace("@", "&#64;").replace("*/", "*&#47;")
        out += "    public %s get%s() {\n        return %s;\n    }\n\n" % (jt, up, prop)
        out += "    /**\n     * Sets {@code %s}.\n     *\n     * @param value the new value\n     */\n" % wire.replace("@", "&#64;").replace("*/", "*&#47;")
        out += "    public void set%s(%s value) {\n        this.%s = value;\n    }\n\n" % (up, jt, prop)
        out += "    /**\n     * Sets {@code %s} and returns this object.\n     *\n     * @param value the new value\n     * @return this\n     */\n" % wire.replace("@", "&#64;").replace("*/", "*&#47;")
        out += "    public %s %s(%s value) {\n        this.%s = value;\n        return this;\n    }\n\n" % (name, prop, jt, prop)
    names = [p for _, p, _ in props]
    out += "    @Override\n    public boolean equals(Object o) {\n"
    out += "        if (this == o) {\n            return true;\n        }\n"
    out += "        if (!(o instanceof %s)) {\n            return false;\n        }\n" % name
    out += "        %s other = (%s) o;\n" % (name, name)
    out += "        return " + "\n            && ".join("Objects.equals(%s, other.%s)" % (n, n) for n in names) + ";\n    }\n\n"
    out += "    @Override\n    public int hashCode() {\n"
    out += "        return Objects.hash(" + ", ".join(names) + ");\n    }\n\n"
    out += "    @Override\n    public String toString() {\n"
    out += '        return "%s" + Json.toJsonString(this);\n    }\n}\n' % name
    return imports_block(imp) + out


def emit_enum(m):
    name = m["name"]
    imp = {"JsonCreator", "JsonValue", "Objects"}
    out = javadoc(m.get("description"))
    if not out:
        out = "/**\n * Open string enum: unknown values decode and round-trip unchanged.\n */\n"
    out += "public final class %s {\n" % name
    used = set()
    consts = []
    for v in m["values"]:
        c = constant_name(v)
        base, i = c, 2
        while c in used or c in ("VALUE",):
            c = "%s_%d" % (base, i)
            i += 1
        used.add(c)
        consts.append((c, v))
    for c, v in consts:
        lit = json.dumps(v)
        out += "    /** The value {@code %s}. */\n" % v.replace("@", "&#64;").replace("*/", "*&#47;").replace("}", "&#125;")
        out += "    public static final %s %s = new %s(%s);\n\n" % (name, c, name, lit)
    out += "    private final String value;\n\n"
    out += "    private %s(String value) {\n        this.value = value;\n    }\n\n" % name
    out += ("    /**\n     * Returns the constant for {@code value}, or a new instance carrying it if it is\n"
            "     * not a known value.\n     *\n     * @param value the wire value\n     * @return the enum value\n     */\n")
    out += "    @JsonCreator\n    public static %s of(String value) {\n" % name
    out += "        if (value == null) {\n            return null;\n        }\n"
    out += "        switch (value) {\n"
    for c, v in consts:
        out += "            case %s:\n                return %s;\n" % (json.dumps(v), c)
    out += "            default:\n                return new %s(value);\n        }\n    }\n\n" % name
    out += "    /**\n     * Returns the wire value.\n     *\n     * @return the string sent to and received from the API\n     */\n"
    out += "    @JsonValue\n    public String value() {\n        return value;\n    }\n\n"
    out += "    /**\n     * Whether this is one of the values known when the SDK was generated.\n     *\n     * @return true for a known value\n     */\n"
    out += "    public boolean isKnown() {\n        switch (value) {\n"
    for c, v in consts:
        out += "            case %s:\n" % json.dumps(v)
    out += "                return true;\n            default:\n                return false;\n        }\n    }\n\n"
    out += "    @Override\n    public boolean equals(Object o) {\n"
    out += "        return o instanceof %s && value.equals(((%s) o).value);\n    }\n\n" % (name, name)
    out += "    @Override\n    public int hashCode() {\n        return Objects.hashCode(value);\n    }\n\n"
    out += "    @Override\n    public String toString() {\n        return value;\n    }\n}\n"
    return imports_block(imp) + out


def emit_union(m):
    name = m["name"]
    imp = {"JsonCreator", "JsonValue", "JsonNode", "Objects", "Json"}
    out = javadoc(m.get("description")) or "/** Union of %s. */\n" % ", ".join(m["variants"])
    out += "public final class %s {\n" % name
    out += "    private final JsonNode raw;\n\n"
    out += ("    /**\n     * Wraps a raw JSON value.\n     *\n     * @param raw the JSON value\n     */\n"
            "    @JsonCreator(mode = JsonCreator.Mode.DELEGATING)\n")
    out += "    public %s(JsonNode raw) {\n        this.raw = raw;\n    }\n\n" % name
    for v in m["variants"]:
        out += ("    /**\n     * Builds the union from a {@link %s}.\n     *\n     * @param value the variant\n"
                "     * @return the union\n     */\n") % v
        out += "    public static %s of(%s value) {\n        return new %s(Json.toTree(value));\n    }\n\n" % (name, v, name)
    out += "    /**\n     * Returns the raw JSON value.\n     *\n     * @return the JSON value\n     */\n"
    out += "    @JsonValue\n    public JsonNode raw() {\n        return raw;\n    }\n\n"
    if m.get("discriminator"):
        d = m["discriminator"]
        out += ("    /**\n     * Returns the {@code %s} discriminator, or null if absent.\n     *\n"
                "     * @return the discriminator value\n     */\n") % d
        out += "    public String discriminator() {\n"
        out += '        JsonNode d = raw == null ? null : raw.get("%s");\n' % d
        out += "        return d == null || d.isNull() ? null : d.asText();\n    }\n\n"
    for v in m["variants"]:
        out += ("    /**\n     * Decodes the value as {@link %s}.\n     *\n     * @return the decoded variant\n"
                "     * @throws one.truto.sdk.TrutoDecodeException if the value does not fit\n     */\n") % v
        out += "    public %s as%s() {\n        return Json.fromTree(raw, %s.class);\n    }\n\n" % (v, v, v)
    out += "    @Override\n    public boolean equals(Object o) {\n"
    out += "        return o instanceof %s && Objects.equals(raw, ((%s) o).raw);\n    }\n\n" % (name, name)
    out += "    @Override\n    public int hashCode() {\n        return Objects.hashCode(raw);\n    }\n\n"
    out += "    @Override\n    public String toString() {\n        return String.valueOf(raw);\n    }\n}\n"
    return imports_block(imp) + out


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: generate_java.py models.json OUTPUT_DIR")
    ir = json.load(open(sys.argv[1]))
    out_dir = sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    written = set()
    for m in ir["models"]:
        name = m["name"]
        if name in RESERVED_CLASS_NAMES:
            sys.exit("model name %s clashes with a class the generated code uses" % name)
        if m["kind"] == "object":
            body = emit_object(m)
        elif m["kind"] == "enum":
            body = emit_enum(m)
        elif m["kind"] == "union":
            body = emit_union(m)
        else:
            sys.exit("unknown model kind %r" % m["kind"])
        src = HEADER + "package %s;\n\n" % PACKAGE + body
        path = os.path.join(out_dir, name + ".java")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(src)
        written.add(name + ".java")
    for fn in os.listdir(out_dir):
        if fn.endswith(".java") and fn not in written:
            p = os.path.join(out_dir, fn)
            with open(p, encoding="utf-8") as fh:
                if fh.readline() == HEADER:
                    os.remove(p)
    print("wrote %d model files to %s" % (len(written), out_dir), file=sys.stderr)


if __name__ == "__main__":
    main()
